#!/bin/sh
set -e

usage() {
    echo "Usage: ./generate_config.sh [--overwrite] [DOMAIN]"
    exit 1
}

OVERWRITE=0
DOMAIN=
for arg in "$@"; do
    case "$arg" in
        --overwrite) OVERWRITE=1 ;;
        -*) usage ;;
        *)
            [ -z "$DOMAIN" ] || usage
            DOMAIN="$arg"
            ;;
    esac
done

# .env may hold settings added by hand (AI keys, publishing secrets), so never replace it silently
if [ -f .env ] && [ "$OVERWRITE" -ne 1 ]; then
    echo "A .env file already exists, so nothing was changed."
    echo "To replace it, run this script again with --overwrite. The current file will be kept as .env.old."
    exit 1
fi

if [ -z "$DOMAIN" ]; then
    printf "Enter your domain (e.g., fuiz.example.com) or 'localhost' for local dev: "
    read -r DOMAIN
fi

if [ -z "$DOMAIN" ]; then
    echo "A domain is required."
    exit 1
fi

BACKED_UP=0
if [ -f .env ]; then
    mv .env .env.old
    BACKED_UP=1
    echo "Moved the existing .env to .env.old"
fi

# Caddy serves HTTPS for every domain, localhost included (with its own local certificate)
DISPLAY_URL="$DOMAIN"
FULL_URL="https://$DOMAIN"
WS_SCHEME="wss"

cat > .env <<EOF
# Generated by generate_config.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")

# Domain configuration
FUIZ_DOMAIN=$DOMAIN

# Frontend environment variables
ORIGIN=$FULL_URL
PUBLIC_DISPLAY_PLAY_URL=$DISPLAY_URL
PUBLIC_PLAY_URL=$FULL_URL
PUBLIC_BACKEND_URL=$FULL_URL/api
PUBLIC_WS_URL=$WS_SCHEME://$DOMAIN/api
PUBLIC_CORKBOARD_URL=$FULL_URL/corkboard

# Game server CORS
FUIZ_ALLOWED_ORIGINS=["$FULL_URL"]

# Corkboard CORS
CORKBOARD_ALLOWED_ORIGINS=["$FULL_URL"]

# AI configuration (optional)
# Uncomment and configure to enable AI-powered tag derivation for library quizzes
# Supports any OpenAI-compatible API (OpenAI, Ollama, OpenRouter, LiteLLM, etc.)
# OPENAI_BASE_URL=http://localhost:11434/v1
# OPENAI_API_KEY=
# AI_MODEL=gpt-4o-mini
EOF

echo "Configuration written to .env"
if [ "$BACKED_UP" -eq 1 ]; then
    echo "Copy any settings you added by hand (such as AI or publishing settings) from .env.old into .env."
fi
echo ""
echo "To start Fuiz, run:"
echo "  docker compose up -d"
